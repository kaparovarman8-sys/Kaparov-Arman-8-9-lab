# --- 3-нұсқа ---

# 1-есеп: 1001 ақпараттық комбинациясы үшін Хэмминг кодын құру
# Бақылау позициялары: 1, 2, 4 (2 индекстері: 0, 1, 3)
# Қалғандары ақпараттық позициялар: 3, 5, 6, 7 -> мәндері: 1, 0, 0, 1
info_bits = [1, 0, 0, 1]  # ақпарат: a3, a5, a6, a7

# Кодтық комбинация макеті (1-ден 7-ге дейін, 0-ге тең уақытша бақылау разрядтарымен)
C = [0, 0, info_bits[0], 0, info_bits[1], info_bits[2], info_bits[3]]

# Жұптық ережесі бойынша бақылау разрядтарын есептеу:
# a1 = a3 ⊕ a5 ⊕ a7
C[0] = C[2] ^ C[4] ^ C[6]
# a2 = a3 ⊕ a6 ⊕ a7
C[1] = C[2] ^ C[5] ^ C[6]
# a4 = a5 ⊕ a6 ⊕ a7
C[3] = C[4] ^ C[5] ^ C[6]

print("1-есептің шешімі:")
print("Дұрыс кодтық комбинация (C):", "".join(map(str, C)))

# --- 2-есеп: 6-разряд бұрмаланды деп есептеу ---
# 6-разряд индекс бойынша 5-ші элемент (C[5])
C_star = list(C)
C_star[5] = 1 - C_star[5]  # Инверсиялау арқылы бұрмалау

print("\n2-есептің шешімі:")
print("Қабылданған комбинация (C*):", "".join(map(str, C_star)))

# Тексеру мәндерін (синдром биттерін) есептеу:
E1 = C_star[0] ^ C_star[2] ^ C_star[4] ^ C_star[6]
E2 = C_star[1] ^ C_star[2] ^ C_star[5] ^ C_star[6]
E3 = C_star[3] ^ C_star[4] ^ C_star[5] ^ C_star[6]

# Синдромды есептеу (екілік және ондық жүйеде)
syndrome_bin = f"{E3}{E2}{E1}"
syndrome_dec = int(syndrome_bin, 2)

print(f"Тексеру мәндері: E1={E1}, E2={E2}, E3={E3}")
print(f"Қатенің бақылау саны (синдромы) екілік жүйеде: {syndrome_bin}")
print(f"Ондық санау жүйесіне аударғанда: {syndrome_dec}-позицияда қате бар.")

# Қатені түзету (инверсиялау)
corrected_C = list(C_star)
corrected_C[syndrome_dec - 1] = 1 - corrected_C[syndrome_dec - 1]
print("Түзетілген кодтық комбинация:", "".join(map(str, corrected_C)))